def clean_text(text):
    text = re.sub(r'\s+', ' ', text).strip()

    # remove repeated ", fairness" or similar tail repeats
    text = re.sub(r',\s*([A-Za-z ]+)\s*,\s*\1$', r', \1', text, flags=re.IGNORECASE)

    # remove duplicate consecutive words
    words = text.split()
    cleaned = []
    for w in words:
        if not cleaned or cleaned[-1].lower() != w.lower():
            cleaned.append(w)

    text = " ".join(cleaned)

    # small cleanup for punctuation spacing
    text = re.sub(r'\s+([,?.])', r'\1', text)

    return text

