def generate_decomposition(question, model, tokenizer, max_length=256):
    input_text = "decompose question: " + question

    inputs = tokenizer(
        input_text,
        return_tensors="pt",
        truncation=True,
        max_length=128
    )
    inputs = {k: v.to(device) for k, v in inputs.items()}

    output_ids = model.generate(
        **inputs,
        max_length=max_length,
        num_beams=5,
        early_stopping=True,
        no_repeat_ngram_size=3,
        repetition_penalty=2.0
    )

    return tokenizer.decode(output_ids[0], skip_special_tokens=True)

